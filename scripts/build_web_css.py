"""Compila design-system/madman (tokens.json + components/bundle.css + app.css) em panel/web/madman.css.

Uso: python scripts/build_web_css.py [--check]
Com --check, falha se panel/web/madman.css estiver desatualizado.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "design-system" / "madman"
OUT = ROOT / "panel" / "web" / "madman.css"

FAMILIES = ("spacing", "radius", "shadow", "zIndex", "ease", "size")


def build() -> str:
    tokens = json.loads((SRC / "tokens.json").read_text(encoding="utf-8"))
    lines = ["/* Madman web panel. Generated by scripts/build_web_css.py from design-system/madman. Do not edit. */", ":root {"]
    for token in tokens["color"]["tokens"]:
        lines.append(f"  --{token['name']}: {token['value']};")
    for family in FAMILIES:
        for token in tokens[family]["tokens"]:
            lines.append(f"  --{token['name']}: {token['value']};")
    lines.append(f"  --font-sans: {tokens['type']['families']['sans']};")
    lines.append("}")
    parts = ["\n".join(lines)]
    for name in ("components/bundle.css", "app.css"):
        parts.append((SRC / name).read_text(encoding="utf-8").strip())
    return "\n\n".join(parts) + "\n"


def main() -> int:
    css = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != css:
            print("panel/web/madman.css desatualizado; rode scripts/build_web_css.py")
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(css)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
